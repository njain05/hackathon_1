// P8: the Reports page (teacher workload, room usage, section load), the
// Excel download of every timetable, and the calendar (.ics) builder.
// Run: npx playwright test e2e/reports.spec.ts --project=desktop

const API = process.env.E2E_API_URL ?? "http://localhost:8000";

let data: CollegeData;
let result: SolveResult;

test.beforeAll(async ({ playwright }) => {
  // The sample college, generated by the real solver.
  const api = await playwright.request.newContext();
  data = await (await api.get(`${API}/sample`)).json();
  result = await (await api.post(`${API}/generate?time_limit=10`, { data })).json();
  expect(result.status).toBe("solved");
  await api.dispose();
});

/** This browser made the timetable: the setup draft and the generated result are in its storage. */
async function seedAdmin(page: Page) {
  await page.addInitScript(
    ([d, r]) => {
      localStorage.setItem("timetable.setup.v1", JSON.stringify(d));
      localStorage.setItem("timetable.result.v1", JSON.stringify({ data: d, result: r, at: new Date().toISOString() }));
    },
    [data, result] as const,
  );
}

test("reports show teacher workload, room usage and section load, and flag the overloaded teacher", async ({ page }) => {
  await seedAdmin(page);
  await page.goto("/reports");
  await expect(page.getByRole("heading", { level: 1, name: "Reports" })).toBeVisible();
  for (const h of ["Teacher workload", "Room usage", "Section load"])
    await expect(page.getByRole("heading", { level: 2, name: h })).toBeVisible();

  // Dr. Harpreet Kaur teaches 14 periods; the CSE average is 78 / 9 = 8.7, so she is 1.6× it and flagged.
  const teachers = page.getByRole("list", { name: "Teachers" }).getByRole("listitem");
  await expect(teachers).toHaveCount(data.teachers.length);
  const hk = teachers.filter({ hasText: "Dr. Harpreet Kaur" });
  await expect(hk).toContainText("14 a week");
  await expect(hk).toContainText("Heavy load: 1.6× the CSE average of 8.7");
  await expect(hk).toContainText(/Busiest \w+day \(\d\), lightest \w+day \((\d|no classes)\)/);
  // Sorted by load: she is first. Dr. Parminder Sandhu (12) is high, but not 1.5× the average.
  await expect(teachers.first()).toContainText("Dr. Harpreet Kaur");
  await expect(teachers.filter({ hasText: "Dr. Parminder Sandhu" })).not.toContainText("Heavy load");
  await expect(page.getByText("1 teacher flagged: Dr. Harpreet Kaur.")).toBeVisible();

  // Sorting by name puts "Dr. Anjali Verma" first.
  await page.getByRole("button", { name: "Name", exact: true }).click();
  await expect(teachers.first()).toContainText("Dr. Anjali Verma");

  // Rooms: classrooms and labs apart; halls and auditoriums never hold classes, so they're left out.
  const classrooms = page.getByRole("list", { name: "Classrooms" }).getByRole("listitem");
  const labs = page.getByRole("list", { name: "Labs" }).getByRole("listitem");
  await expect(classrooms).toHaveCount(6);
  await expect(labs).toHaveCount(3);
  await expect(labs.filter({ hasText: "Computer Lab 1" })).toContainText(/\d+ of 35 periods/);
  await expect(page.getByRole("main")).not.toContainText("Seminar Hall");
  await expect(page.getByRole("heading", { name: "Could be freed for other uses" })).toBeVisible();

  // Sections: periods out of the 35 in the week, and the free ones.
  const sections = page.getByRole("list", { name: "Sections" }).getByRole("listitem");
  await expect(sections).toHaveCount(5);
  await expect(sections.filter({ hasText: "CSE 3rd Sem A" })).toContainText(/\d+ of 35/);
  await expect(sections.filter({ hasText: "CSE 3rd Sem A" })).toContainText(/\d+ free periods?/);

  await page.screenshot({ path: "test-results/reports/desktop-reports.png", fullPage: true });
});

