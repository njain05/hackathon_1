test("Download Excel gives one sheet per section, teacher and room, with clock times and merged labs", async ({ page }) => {
  await seedAdmin(page);
  await page.goto("/reports");
  const [download] = await Promise.all([
    page.waitForEvent("download"),
    page.getByRole("button", { name: "Download Excel (all timetables)" }).click(),
  ]);
  expect(download.suggestedFilename()).toMatch(/-timetables\.xlsx$/);
  const wb = XLSX.read(readFileSync(await download.path()));

  const uses = new Map(data.room_types.map((t) => [t.id, t.use]));
  const classRooms = data.rooms.filter((r) => uses.get(r.type) !== "event");
  expect(wb.SheetNames[0]).toBe("Contents");
  expect(wb.SheetNames).toHaveLength(1 + data.sections.length + data.teachers.length + classRooms.length);
  expect(wb.SheetNames).toEqual(expect.arrayContaining(["Section CSE-3A", "Teacher HK", "Room LT-1", "Room CL-1"]));
  expect(wb.SheetNames).not.toContain("Room SH-1");
  for (const name of wb.SheetNames) expect(name.length).toBeLessThanOrEqual(31);

  const ws = wb.Sheets["Section CSE-3A"];
  const rows = XLSX.utils.sheet_to_json<string[]>(ws, { header: 1, defval: "", raw: false });
  expect(rows[0][0]).toBe("Section: CSE-3A – CSE 3rd Sem A");
  expect(rows[3].slice(0, 4)).toEqual(["Day", "Period 1 (09:00–09:50)", "Period 2 (09:50–10:40)", "Tea break (10:40–10:50)"]);
  expect(rows[3]).toContain("Lunch (12:30–13:10)");
  expect(rows.slice(4, 9).map((r) => r[0])).toEqual(data.settings.days);
  const cells = rows.slice(4, 9).flat();
  expect(cells.some((c) => /^CS\d+ .+ \(Lab\) \/ .+ \/ .*Lab/.test(c))).toBeTruthy();
  expect(cells.some((c) => /^\w+\d+ .+ \/ .+ \/ .+/.test(c) && !c.includes("(Lab)"))).toBeTruthy();
  // Each 2-period lab is one merged cell (plus the title row's merge).
  const labMerges = (ws["!merges"] ?? []).filter((m) => m.s.r >= 4 && m.e.c > m.s.c);
  const labPeriods = entriesFor(result.entries, "section", "CSE-3A").filter((e) => e.kind === "lab").length;
  expect(labMerges).toHaveLength(labPeriods / 2);
});

test("calendar file: one weekly event per class, labs merged, RFC 5545 line rules", () => {
  const mine = entriesFor(result.entries, "section", "CSE-3A");
  const from = new Date(2026, 10, 2); // Monday 2 November 2026
  const opts = { from, weeks: 16, now: new Date(Date.UTC(2026, 9, 27, 12, 0, 0)) };
  const ics = icsForEntries(data, mine, "section", "CSE-3A – CSE 3rd Sem A", opts);

  // CRLF everywhere, every physical line at most 75 octets, the file ends with CRLF.
  expect(ics.endsWith("\r\n")).toBeTruthy();
  expect(ics.replace(/\r\n/g, "").includes("\n")).toBeFalsy();
  for (const line of ics.split("\r\n")) expect(Buffer.byteLength(line, "utf8")).toBeLessThanOrEqual(75);
  expect(ics.startsWith("BEGIN:VCALENDAR\r\nVERSION:2.0\r\nPRODID:")).toBeTruthy();

  const unfolded = ics.replace(/\r\n /g, "");
  const events = unfolded.split("BEGIN:VEVENT").slice(1).map((block) => {
    const get = (k: string) => block.match(new RegExp(`\\r\\n${k}:([^\\r]*)`))?.[1] ?? "";
    return { uid: get("UID"), start: get("DTSTART"), end: get("DTEND"), rrule: get("RRULE"), summary: get("SUMMARY"), location: get("LOCATION"), description: get("DESCRIPTION") };
  });
  const classCells = buildRows(data, mine).rows.flatMap((r) => r.cells.filter((c) => c.type === "class"));
  expect(events).toHaveLength(classCells.length);
  expect(new Set(events.map((e) => e.uid)).size).toBe(events.length);
  for (const e of events) {
    expect(e.rrule).toBe("FREQ=WEEKLY;COUNT=16");
    expect(e.start).toMatch(/^2026110[2-6]T\d{4}00$/); // Monday 2 to Friday 6 November, floating time
    expect(e.location).not.toBe("");
    expect(e.description).toMatch(/^Teacher: /);
  }
  // Monday classes start on Monday 2 November, Friday ones on Friday 6 November.
  const mondayClasses = buildRows(data, mine).rows.find((r) => r.day === "Monday")!.cells.filter((c) => c.type === "class").length;
  expect(events.filter((e) => e.start.startsWith("20261102"))).toHaveLength(mondayClasses);

  // A 2-period lab is one event: "CS201 Data Structures (Lab)", 100 minutes (110 if it runs across the tea break).
  const labs = events.filter((e) => e.summary.endsWith("(Lab)"));
  expect(labs.length).toBe(mine.filter((e) => e.kind === "lab").length / 2);
  const minutes = (t: string) => Number(t.slice(9, 11)) * 60 + Number(t.slice(11, 13));
  for (const l of labs) expect([100, 110]).toContain(minutes(l.end) - minutes(l.start));
  expect(labs.some((l) => /^CS\d+ [A-Z].* \(Lab\)$/.test(l.summary))).toBeTruthy();

  // Same classes, later download: the same UIDs, so a calendar can recognise them.
  const again = icsForEntries(data, mine, "section", "CSE-3A – CSE 3rd Sem A", { ...opts, now: new Date() });
  const uids = (s: string) => [...s.replace(/\r\n /g, "").matchAll(/UID:([^\r]+)/g)].map((m) => m[1]);
  expect(uids(again)).toEqual(uids(ics));

  // Starting mid-week: Monday's classes begin the following Monday.
  const wed = icsForEntries(data, mine, "section", "CSE-3A", { ...opts, from: new Date(2026, 10, 4) });
  const starts = [...wed.matchAll(/DTSTART:(\d{8})/g)].map((m) => m[1]);
  expect(starts.every((s) => s >= "20261104" && s <= "20261110")).toBeTruthy();
  expect(starts).toContain("20261109");

  // Escaping and folding.
  expect(icsEscape("Lab 1, Block A; see\\notes\nnext")).toBe("Lab 1\\, Block A\\; see\\\\notes\\nnext");
  const long = `DESCRIPTION:${"Périodes – ".repeat(20)}`;
  const folded = foldLine(long);
  for (const part of folded.split("\r\n")) expect(Buffer.byteLength(part, "utf8")).toBeLessThanOrEqual(75);
  expect(folded.replace(/\r\n /g, "")).toBe(long);
});

test("open electives and lab batches read well in the calendar and the workbook", () => {
  // A small made-up week on top of the sample: an open elective for two sections, and a lab split into two batches.
  const d: CollegeData = {
    ...data,
    elective_groups: [
      {
        id: "OE1",
        name: "Open Elective I",
        section_ids: ["CSE-3A", "ECE-3A"],
        periods_per_week: 1,
        options: [
          { subject_id: "CS201", teacher_id: "HK", students: 30 },
          { subject_id: "MA201", teacher_id: "PS", students: 30 },
        ],
      },
    ],
  };
  const base = { day: "Monday", period: 5, section_id: "OE1", kind: "elective" as const, elective_group: "OE1", elective_sections: ["CSE-3A", "ECE-3A"] };
  const batch = (b: string, room: string, teacher: string): Entry =>
    ({ day: "Tuesday", period: 1, section_id: "CSE-3A", subject_id: "CS201", teacher_id: teacher, room_id: room, kind: "lab", batch: b }) as Entry;
  const entries: Entry[] = [
    { ...base, subject_id: "CS201", teacher_id: "HK", room_id: "C-101" },
    { ...base, subject_id: "MA201", teacher_id: "PS", room_id: "E-201" },
    batch("A1", "CL-1", "HK"),
    batch("A2", "CL-2", "NS"),
    { ...batch("A1", "CL-1", "HK"), period: 2 },
    { ...batch("A2", "CL-2", "NS"), period: 2 },
  ];
  const mine = entriesFor(entries, "section", "CSE-3A");
  expect(mine).toHaveLength(6);
  const ics = icsForEntries(d, mine, "section", "CSE-3A", { from: new Date(2026, 10, 2), weeks: 4 }).replace(/\r\n /g, "");
  expect(ics.match(/BEGIN:VEVENT/g)).toHaveLength(2);
  expect(ics).toContain("SUMMARY:Open Elective I (Elective)");
  expect(ics).toContain("LOCATION:Room C-101\\, Room E-201");
  expect(ics).toContain("CS201 Data Structures: Dr. Harpreet Kaur\\, Room C-101");
  // Both batches in one 2-period lab event (09:00 to the end of period 2), each with their teacher and lab.
  expect(ics).toMatch(/DTSTART:20261103T090000\r\nDTEND:20261103T104000\r\nRRULE:FREQ=WEEKLY;COUNT=4\r\nSUMMARY:CS201 Data Structures \(Lab\)\r\nLOCATION:Computer Lab 1\\, Computer Lab 2/);
  expect(ics).toContain("Batch A1: Teacher: Dr. Harpreet Kaur\\, Computer Lab 1");

  const n = lookup(d);
  const elective = cellText(mine.filter((e) => e.kind === "elective"), "section", n);
  expect(elective).toBe(
    "Open Elective I (Elective), choose one: CS201 Data Structures / Dr. Harpreet Kaur / Room C-101; MA201 Discrete Mathematics / Dr. Parminder Sandhu / Room E-201",
  );
  expect(cellText(mine.filter((e) => e.kind === "lab" && e.period === 1), "section", n)).toContain("Batch A1: CS201 Data Structures (Lab) / Dr. Harpreet Kaur / Computer Lab 1");
  // The workbook builds with the elective (its group appears in the key).
  const wb = timetableWorkbook(d, { ...result, entries });
  const rows = XLSX.utils.sheet_to_json<string[]>(wb.Sheets["Section CSE-3A"], { header: 1, defval: "" });
  expect(rows.flat()).toContain("Open Elective I");

  // Excel sheet names: forbidden characters replaced, 31 characters at most, unique ignoring case.
  const taken = new Set<string>();
  expect(sheetName("Section A/B: [x]?*", taken)).toBe("Section A-B- -x---");
  expect(sheetName("Teacher " + "x".repeat(40), taken)).toHaveLength(31);
  expect(sheetName("section a/b: [x]?*", taken)).toBe("section a-b- -x--- (2)");
  expect(sheetName("'History'", taken)).toBe("History 1");
});
